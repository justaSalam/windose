"""
LVGL (Lightweight Versatile Graphics Library) C code generator.
Outputs ready-to-compile C code and header for Linux/ELF and embedded targets.
"""

from typing import List
from core.models import Project, Widget, WidgetType


def hex_to_lv_color(hex_str: str) -> str:
    """Converts #RRGGBB to 0xRRGGBB."""
    clean = hex_str.lstrip("#")
    if len(clean) == 6:
        return f"0x{clean.upper()}"
    return "0x1E293B"


def generate_lvgl_c(project: Project) -> str:
    """Generates LVGL C source code for the project."""
    c_code = []
    c_code.append("/**")
    c_code.append(f" * Generated by ELF Studio - GUI Designer for ELF Programs")
    c_code.append(f" * Target: LVGL C99 (Linux Desktop / Embedded ELF)")
    c_code.append(f" * Screen: {project.name} ({project.canvas_width}x{project.canvas_height})")
    c_code.append(" */\n")
    c_code.append('#include "lvgl.h"')
    c_code.append('#include <stdio.h>\n')

    # Widget object declarations
    c_code.append("/* UI Element References */")
    c_code.append("static lv_obj_t *main_screen;")
    for w in project.widgets:
        c_code.append(f"static lv_obj_t *ui_{w.name};")
    c_code.append("")

    # Event callbacks
    c_code.append("/* Event Handlers */")
    seen_handlers = set()
    for w in project.widgets:
        handler = w.event_handler or f"on_{w.name}_event"
        if handler not in seen_handlers:
            seen_handlers.add(handler)
            c_code.append(f"static void {handler}(lv_event_t *e) {{")
            c_code.append(f"    lv_obj_t *target = lv_event_get_target(e);")
            c_code.append(f'    printf("[LVGL EVENT] {handler} triggered on %p\\n", (void*)target);')
            if w.widget_type == WidgetType.BUTTON:
                c_code.append(f'    // Button clicked logic here')
            elif w.widget_type == WidgetType.SLIDER:
                c_code.append(f"    int val = lv_slider_get_value(target);")
                c_code.append(f'    printf("  -> Slider new value: %d\\n", val);')
            elif w.widget_type in (WidgetType.CHECKBOX, WidgetType.SWITCH):
                c_code.append(f"    bool state = lv_obj_has_state(target, LV_STATE_CHECKED);")
                c_code.append(f'    printf("  -> State toggled: %s\\n", state ? "ON" : "OFF");')
            c_code.append("}\n")

    # Main initialization function
    c_code.append("/* Initialize UI */")
    c_code.append(f"void ui_{project.name.lower()}_init(void) {{")
    c_code.append("    /* Base Screen */")
    c_code.append("    main_screen = lv_obj_create(NULL);")
    c_code.append(f"    lv_obj_set_size(main_screen, {project.canvas_width}, {project.canvas_height});")
    c_code.append(f"    lv_obj_set_style_bg_color(main_screen, lv_color_hex({hex_to_lv_color(project.bg_color)}), LV_PART_MAIN);")
    c_code.append("    lv_obj_set_style_bg_opa(main_screen, LV_OPA_COVER, LV_PART_MAIN);")
    c_code.append("    lv_scr_load(main_screen);\n")

    for w in project.widgets:
        c_code.append(f"    /* --- Widget: {w.name} ({w.widget_type}) --- */")
        color_hex = hex_to_lv_color(w.bg_color)
        text_color_hex = hex_to_lv_color(w.text_color)
        border_color_hex = hex_to_lv_color(w.border_color)

        if w.widget_type == WidgetType.PANEL:
            c_code.append(f"    ui_{w.name} = lv_obj_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            c_code.append(f"    lv_obj_set_style_bg_color(ui_{w.name}, lv_color_hex({color_hex}), LV_PART_MAIN);")
            c_code.append(f"    lv_obj_set_style_radius(ui_{w.name}, {w.corner_radius}, LV_PART_MAIN);")
            c_code.append(f"    lv_obj_set_style_border_color(ui_{w.name}, lv_color_hex({border_color_hex}), LV_PART_MAIN);")
            c_code.append(f"    lv_obj_set_style_border_width(ui_{w.name}, {w.border_width}, LV_PART_MAIN);")

        elif w.widget_type == WidgetType.BUTTON:
            c_code.append(f"    ui_{w.name} = lv_btn_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            c_code.append(f"    lv_obj_set_style_bg_color(ui_{w.name}, lv_color_hex({color_hex}), LV_PART_MAIN);")
            c_code.append(f"    lv_obj_set_style_radius(ui_{w.name}, {w.corner_radius}, LV_PART_MAIN);")
            c_code.append(f"    lv_obj_set_style_border_color(ui_{w.name}, lv_color_hex({border_color_hex}), LV_PART_MAIN);")
            c_code.append(f"    lv_obj_set_style_border_width(ui_{w.name}, {w.border_width}, LV_PART_MAIN);")
            c_code.append(f"    lv_obj_add_event_cb(ui_{w.name}, {w.event_handler}, LV_EVENT_CLICKED, NULL);")
            # Label inside button
            c_code.append(f"    lv_obj_t *lbl_{w.name} = lv_label_create(ui_{w.name});")
            c_code.append(f'    lv_label_set_text(lbl_{w.name}, "{w.text}");')
            c_code.append(f"    lv_obj_set_style_text_color(lbl_{w.name}, lv_color_hex({text_color_hex}), LV_PART_MAIN);")
            c_code.append(f"    lv_obj_center(lbl_{w.name});")

        elif w.widget_type == WidgetType.LABEL:
            c_code.append(f"    ui_{w.name} = lv_label_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            c_code.append(f'    lv_label_set_text(ui_{w.name}, "{w.text}");')
            c_code.append(f"    lv_obj_set_style_text_color(ui_{w.name}, lv_color_hex({text_color_hex}), LV_PART_MAIN);")

        elif w.widget_type == WidgetType.ENTRY:
            c_code.append(f"    ui_{w.name} = lv_textarea_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            c_code.append(f"    lv_textarea_set_one_line(ui_{w.name}, true);")
            c_code.append(f'    lv_textarea_set_placeholder_text(ui_{w.name}, "{w.text}");')
            c_code.append(f"    lv_obj_set_style_bg_color(ui_{w.name}, lv_color_hex({color_hex}), LV_PART_MAIN);")
            c_code.append(f"    lv_obj_set_style_text_color(ui_{w.name}, lv_color_hex({text_color_hex}), LV_PART_MAIN);")

        elif w.widget_type == WidgetType.TEXTAREA:
            c_code.append(f"    ui_{w.name} = lv_textarea_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            c_code.append(f'    lv_textarea_set_text(ui_{w.name}, "{w.text}");')
            c_code.append(f"    lv_obj_set_style_bg_color(ui_{w.name}, lv_color_hex({color_hex}), LV_PART_MAIN);")

        elif w.widget_type == WidgetType.SLIDER:
            c_code.append(f"    ui_{w.name} = lv_slider_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            c_code.append(f"    lv_slider_set_range(ui_{w.name}, {int(w.min_val)}, {int(w.max_val)});")
            c_code.append(f"    lv_slider_set_value(ui_{w.name}, {int(w.value or 50)}, LV_ANIM_OFF);")
            c_code.append(f"    lv_obj_add_event_cb(ui_{w.name}, {w.event_handler}, LV_EVENT_VALUE_CHANGED, NULL);")

        elif w.widget_type == WidgetType.PROGRESSBAR:
            c_code.append(f"    ui_{w.name} = lv_bar_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            c_code.append(f"    lv_bar_set_range(ui_{w.name}, {int(w.min_val)}, {int(w.max_val)});")
            c_code.append(f"    lv_bar_set_value(ui_{w.name}, {int(w.value or 50)}, LV_ANIM_OFF);")

        elif w.widget_type == WidgetType.CHECKBOX:
            c_code.append(f"    ui_{w.name} = lv_checkbox_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f'    lv_checkbox_set_text(ui_{w.name}, "{w.text}");')
            if w.value:
                c_code.append(f"    lv_obj_add_state(ui_{w.name}, LV_STATE_CHECKED);")
            c_code.append(f"    lv_obj_add_event_cb(ui_{w.name}, {w.event_handler}, LV_EVENT_VALUE_CHANGED, NULL);")

        elif w.widget_type == WidgetType.SWITCH:
            c_code.append(f"    ui_{w.name} = lv_switch_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            if w.value:
                c_code.append(f"    lv_obj_add_state(ui_{w.name}, LV_STATE_CHECKED);")
            c_code.append(f"    lv_obj_add_event_cb(ui_{w.name}, {w.event_handler}, LV_EVENT_VALUE_CHANGED, NULL);")

        elif w.widget_type == WidgetType.DROPDOWN:
            c_code.append(f"    ui_{w.name} = lv_dropdown_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            opts = "\\n".join(w.options) if w.options else "Option 1\\nOption 2"
            c_code.append(f'    lv_dropdown_set_options(ui_{w.name}, "{opts}");')

        elif w.widget_type == WidgetType.STATUSBAR:
            c_code.append(f"    ui_{w.name} = lv_obj_create(main_screen);")
            c_code.append(f"    lv_obj_set_pos(ui_{w.name}, {w.x}, {w.y});")
            c_code.append(f"    lv_obj_set_size(ui_{w.name}, {w.width}, {w.height});")
            c_code.append(f"    lv_obj_set_style_bg_color(ui_{w.name}, lv_color_hex({color_hex}), LV_PART_MAIN);")
            c_code.append(f"    lv_obj_t *s_lbl_{w.name} = lv_label_create(ui_{w.name});")
            c_code.append(f'    lv_label_set_text(s_lbl_{w.name}, "{w.text}");')
            c_code.append(f"    lv_obj_set_style_text_color(s_lbl_{w.name}, lv_color_hex({text_color_hex}), LV_PART_MAIN);")

        c_code.append("")

    c_code.append("}")
    return "\n".join(c_code)
