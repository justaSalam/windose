"""
Cosmos OS C# Canvas UI Generator.
Generates Screen drawing code for Cosmos OS kernels (x86 ELF binary targets).
"""

from core.models import Project, Widget, WidgetType


def hex_to_cosmos_color(hex_str: str) -> str:
    """Converts #RRGGBB to Color.FromArgb(255, r, g, b)."""
    clean = hex_str.lstrip("#")
    if len(clean) == 6:
        r = int(clean[0:2], 16)
        g = int(clean[2:4], 16)
        b = int(clean[4:6], 16)
        return f"Color.FromArgb(255, {r}, {g}, {b})"
    return "Color.DarkSlateGray"


def generate_cosmos_cs(project: Project) -> str:
    """Generates Cosmos OS C# code for the Canvas UI."""
    lines = []
    lines.append("/**")
    lines.append(f" * Generated by ELF Studio - Cosmos OS Canvas UI")
    lines.append(f" * Target: Cosmos C# Kernel (x86 / ELF / ISO)")
    lines.append(f" * Resolution: {project.canvas_width}x{project.canvas_height}")
    lines.append(" */\n")
    lines.append("using System;")
    lines.append("using System.Drawing;")
    lines.append("using Cosmos.System.Graphics;\n")
    lines.append("namespace CosmosKernel.UI")
    lines.append("{")
    lines.append(f"    public static class {project.name}Screen")
    lines.append("    {")
    lines.append(f"        public const int ScreenWidth = {project.canvas_width};")
    lines.append(f"        public const int ScreenHeight = {project.canvas_height};\n")
    lines.append("        public static void Draw(Canvas canvas)")
    lines.append("        {")
    lines.append(f"            // Clear Background")
    lines.append(f"            canvas.Clear({hex_to_cosmos_color(project.bg_color)});\n")

    for w in project.widgets:
        lines.append(f"            // {w.name} ({w.widget_type})")
        col = hex_to_cosmos_color(w.bg_color)
        pen = hex_to_cosmos_color(w.border_color)
        tcol = hex_to_cosmos_color(w.text_color)

        if w.widget_type in (WidgetType.PANEL, WidgetType.BUTTON):
            lines.append(f"            canvas.DrawFilledRectangle(new Pen({col}), {w.x}, {w.y}, {w.width}, {w.height});")
            lines.append(f"            canvas.DrawRectangle(new Pen({pen}), {w.x}, {w.y}, {w.width}, {w.height});")
            if w.text:
                lines.append(f'            canvas.DrawString("{w.text}", Color.White, {w.x + 8}, {w.y + w.height//2 - 6});')

        elif w.widget_type == WidgetType.LABEL:
            lines.append(f'            canvas.DrawString("{w.text}", {tcol}, {w.x}, {w.y});')

        elif w.widget_type in (WidgetType.ENTRY, WidgetType.TEXTAREA):
            lines.append(f"            canvas.DrawFilledRectangle(new Pen({col}), {w.x}, {w.y}, {w.width}, {w.height});")
            lines.append(f"            canvas.DrawRectangle(new Pen({pen}), {w.x}, {w.y}, {w.width}, {w.height});")
            txt = w.text or w.placeholder
            if txt:
                lines.append(f'            canvas.DrawString("{txt}", {tcol}, {w.x + 6}, {w.y + 6});')

        elif w.widget_type in (WidgetType.CHECKBOX, WidgetType.RADIO, WidgetType.SWITCH):
            lines.append(f"            canvas.DrawRectangle(new Pen({pen}), {w.x}, {w.y + w.height//2 - 8}, 16, 16);")
            if w.value:
                lines.append(f"            canvas.DrawFilledRectangle(new Pen(Color.FromArgb(255, 37, 99, 235)), {w.x + 3}, {w.y + w.height//2 - 5}, 10, 10);")
            lines.append(f'            canvas.DrawString("{w.text}", {tcol}, {w.x + 22}, {w.y + w.height//2 - 6});')

        elif w.widget_type == WidgetType.SLIDER:
            lines.append(f"            canvas.DrawFilledRectangle(new Pen(Color.FromArgb(255, 51, 65, 85)), {w.x}, {w.y + w.height//2 - 2}, {w.width}, 4);")
            fill_w = int(w.width * (float(w.value or 50) / 100.0))
            lines.append(f"            canvas.DrawFilledRectangle(new Pen(Color.FromArgb(255, 59, 130, 246)), {w.x}, {w.y + w.height//2 - 2}, {fill_w}, 4);")

        elif w.widget_type == WidgetType.PROGRESSBAR:
            lines.append(f"            canvas.DrawRectangle(new Pen({pen}), {w.x}, {w.y}, {w.width}, {w.height});")
            bar_w = int(w.width * (float(w.value or 50) / 100.0))
            lines.append(f"            canvas.DrawFilledRectangle(new Pen(Color.FromArgb(255, 16, 185, 129)), {w.x}, {w.y}, {bar_w}, {w.height});")

        elif w.widget_type == WidgetType.SEPARATOR:
            lines.append(f"            canvas.DrawLine(new Pen({pen}), {w.x}, {w.y + w.height//2}, {w.x + w.width}, {w.y + w.height//2});")

        elif w.widget_type in (WidgetType.LISTBOX, WidgetType.DATAGRID, WidgetType.TABS):
            lines.append(f"            canvas.DrawFilledRectangle(new Pen({col}), {w.x}, {w.y}, {w.width}, {w.height});")
            lines.append(f"            canvas.DrawRectangle(new Pen({pen}), {w.x}, {w.y}, {w.width}, {w.height});")
            lines.append(f'            canvas.DrawString("{w.text}", {tcol}, {w.x + 8}, {w.y + 6});')

        elif w.widget_type == WidgetType.STATUSBAR:
            lines.append(f"            canvas.DrawFilledRectangle(new Pen({col}), {w.x}, {w.y}, {w.width}, {w.height});")
            lines.append(f'            canvas.DrawString("{w.text}", {tcol}, {w.x + 8}, {w.y + 4});')

        else:
            lines.append(f"            canvas.DrawFilledRectangle(new Pen({col}), {w.x}, {w.y}, {w.width}, {w.height});")
            lines.append(f"            canvas.DrawRectangle(new Pen({pen}), {w.x}, {w.y}, {w.width}, {w.height});")
            if w.text:
                lines.append(f'            canvas.DrawString("{w.text}", {tcol}, {w.x + 4}, {w.y + 4});')

        lines.append("")

    lines.append("            canvas.Display();")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines)
