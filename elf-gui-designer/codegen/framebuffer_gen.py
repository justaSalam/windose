"""
Standalone Linux Framebuffer / Bare-Metal C code generator.
Generates completely self-contained C code with zero external GUI dependencies.
Renders directly to /dev/fb0 or a raw RGB32 pixel buffer.
Can be cross-compiled to an ELF binary directly with Clang/LLD on Windows!
"""

from core.models import Project, Widget, WidgetType


def hex_to_rgb32(hex_str: str) -> str:
    """Converts #RRGGBB to 0x00RRGGBB integer."""
    clean = hex_str.lstrip("#")
    if len(clean) == 6:
        return f"0x00{clean.upper()}"
    return "0x001E293B"


def generate_framebuffer_c(project: Project) -> str:
    """Generates self-contained C code for Linux Framebuffer / OS-dev ELF binary."""
    lines = []
    lines.append("/**")
    lines.append(f" * Generated by ELF Studio - Standalone Framebuffer GUI for ELF Binaries")
    lines.append(f" * Self-contained: No X11, Wayland, or GTK needed!")
    lines.append(f" * Target: Linux /dev/fb0 or OS Kernel Framebuffer")
    lines.append(f" * Resolution: {project.canvas_width} x {project.canvas_height}")
    lines.append(" */\n")
    lines.append("#include <stdint.h>")
    lines.append("#include <stdbool.h>")
    lines.append("#include <stddef.h>\n")
    lines.append("/* Simple 8x8 font lookup table (ASCII subset 32..126) */")
    lines.append("static const uint8_t font8x8_basic[95][8] = {")
    lines.append("    {0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00}, /* Space */")
    lines.append("    {0x18,0x3C,0x3C,0x18,0x18,0x00,0x18,0x00}, /* ! */")
    lines.append("    {0x66,0x66,0x24,0x00,0x00,0x00,0x00,0x00}, /* \" */")
    lines.append("    {0x6C,0x6C,0xFE,0x6C,0xFE,0x6C,0x6C,0x00}, /* # */")
    lines.append("    {0x18,0x3E,0x60,0x3C,0x06,0x7C,0x18,0x00}, /* $ */")
    lines.append("    {0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00}, /* Default */")
    lines.append("}; // Minimal font fallback\n")

    lines.append("/* Framebuffer Drawing Context */")
    lines.append("typedef struct {")
    lines.append("    uint32_t *buffer;")
    lines.append("    uint32_t width;")
    lines.append("    uint32_t height;")
    lines.append("    uint32_t pitch;")
    lines.append("} fb_ctx_t;\n")

    lines.append("static inline void fb_put_pixel(fb_ctx_t *ctx, int x, int y, uint32_t color) {")
    lines.append("    if (x >= 0 && x < (int)ctx->width && y >= 0 && y < (int)ctx->height) {")
    lines.append("        ctx->buffer[y * (ctx->pitch / 4) + x] = color;")
    lines.append("    }")
    lines.append("}\n")

    lines.append("void fb_fill_rect(fb_ctx_t *ctx, int x, int y, int w, int h, uint32_t color) {")
    lines.append("    for (int cy = y; cy < y + h; cy++) {")
    lines.append("        for (int cx = x; cx < x + w; cx++) {")
    lines.append("            fb_put_pixel(ctx, cx, cy, color);")
    lines.append("        }")
    lines.append("    }")
    lines.append("}\n")

    lines.append("void fb_draw_rect_outline(fb_ctx_t *ctx, int x, int y, int w, int h, uint32_t color, int thickness) {")
    lines.append("    fb_fill_rect(ctx, x, y, w, thickness, color);")
    lines.append("    fb_fill_rect(ctx, x, y + h - thickness, w, thickness, color);")
    lines.append("    fb_fill_rect(ctx, x, y, thickness, h, color);")
    lines.append("    fb_fill_rect(ctx, x + w - thickness, y, thickness, h, color);")
    lines.append("}\n")

    lines.append("/* Render the Full Screen UI */")
    lines.append(f"void render_{project.name.lower()}_ui(fb_ctx_t *ctx) {{")
    lines.append(f"    /* Screen Background */")
    lines.append(f"    fb_fill_rect(ctx, 0, 0, {project.canvas_width}, {project.canvas_height}, {hex_to_rgb32(project.bg_color)});\n")

    for w in project.widgets:
        bg = hex_to_rgb32(w.bg_color)
        border = hex_to_rgb32(w.border_color)
        text_col = hex_to_rgb32(w.text_color)
        lines.append(f"    /* {w.name} ({w.widget_type}) */")

        if w.widget_type == WidgetType.PANEL:
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {bg});")
            lines.append(f"    fb_draw_rect_outline(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {border}, {w.border_width});")

        elif w.widget_type == WidgetType.BUTTON:
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {bg});")
            lines.append(f"    fb_draw_rect_outline(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {border}, 1);")

        elif w.widget_type == WidgetType.ENTRY:
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {bg});")
            lines.append(f"    fb_draw_rect_outline(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {border}, 1);")

        elif w.widget_type == WidgetType.SLIDER:
            lines.append(f"    /* Track */")
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y + w.height//2 - 3}, {w.width}, 6, 0x00334155);")
            fill_w = int(w.width * (float(w.value or 50) / 100.0))
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y + w.height//2 - 3}, {fill_w}, 6, 0x003B82F6);")
            lines.append(f"    /* Thumb knob */")
            lines.append(f"    fb_fill_rect(ctx, {w.x + fill_w - 6}, {w.y + w.height//2 - 10}, 12, 20, 0x00FFFFFF);")

        elif w.widget_type == WidgetType.PROGRESSBAR:
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y}, {w.width}, {w.height}, 0x001E293B);")
            bar_w = int(w.width * (float(w.value or 50) / 100.0))
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y}, {bar_w}, {w.height}, 0x0010B981);")
            lines.append(f"    fb_draw_rect_outline(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {border}, 1);")

        elif w.widget_type == WidgetType.CHECKBOX:
            lines.append(f"    /* Box */")
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y + w.height//2 - 10}, 20, 20, 0x001E293B);")
            lines.append(f"    fb_draw_rect_outline(ctx, {w.x}, {w.y + w.height//2 - 10}, 20, 20, 0x003B82F6, 2);")
            if w.value:
                lines.append(f"    fb_fill_rect(ctx, {w.x + 4}, {w.y + w.height//2 - 6}, 12, 12, 0x003B82F6);")

        elif w.widget_type == WidgetType.STATUSBAR:
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {bg});")

        else:
            lines.append(f"    fb_fill_rect(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {bg});")
            lines.append(f"    fb_draw_rect_outline(ctx, {w.x}, {w.y}, {w.width}, {w.height}, {border}, 1);")

    lines.append("}\n")
    lines.append("/* Standalone ELF Entry Point (Freestanding Linux syscall exit) */")
    lines.append("void _start(void) {")
    lines.append("    // When running inside a kernel or freestanding environment,")
    lines.append("    // pass your framebuffer pointer to render_" + project.name.lower() + "_ui(&ctx);")
    lines.append("    __asm__ volatile (")
    lines.append('        "mov $60, %rax\\n"')
    lines.append('        "mov $0, %rdi\\n"')
    lines.append('        "syscall\\n"')
    lines.append("    );")
    lines.append("}")
    return "\n".join(lines)
