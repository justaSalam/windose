"""
GTK+ 3 C code generator.
Generates native Linux desktop ELF application using standard GTK 3 C APIs.
"""

from core.models import Project, Widget, WidgetType


def generate_gtk_c(project: Project) -> str:
    """Generates GTK 3 C code for the project."""
    lines = []
    lines.append("/**")
    lines.append(f" * Generated by ELF Studio - Linux Desktop GTK 3 ELF Application")
    lines.append(f" * Compile on Linux: gcc `pkg-config --cflags gtk+-3.0` main.c `pkg-config --libs gtk+-3.0` -o {project.name.lower()}.elf")
    lines.append(" */\n")
    lines.append("#include <gtk/gtk.h>\n")

    # Callbacks
    seen = set()
    for w in project.widgets:
        if w.widget_type == WidgetType.BUTTON:
            handler = w.event_handler or f"on_{w.name}_clicked"
            if handler not in seen:
                seen.add(handler)
                lines.append(f"static void {handler}(GtkWidget *widget, gpointer data) {{")
                lines.append(f'    g_print("[GTK EVENT] Button \'{w.name}\' clicked!\\n");')
                lines.append("}\n")

    lines.append("static void activate(GtkApplication *app, gpointer user_data) {")
    lines.append("    GtkWidget *window;")
    lines.append("    GtkWidget *fixed;\n")
    lines.append("    window = gtk_application_window_new(app);")
    lines.append(f'    gtk_window_set_title(GTK_WINDOW(window), "{project.name} - Linux ELF");')
    lines.append(f"    gtk_window_set_default_size(GTK_WINDOW(window), {project.canvas_width}, {project.canvas_height});")
    lines.append("    gtk_window_set_resizable(GTK_WINDOW(window), FALSE);\n")
    lines.append("    fixed = gtk_fixed_new();")
    lines.append("    gtk_container_add(GTK_CONTAINER(window), fixed);\n")

    for w in project.widgets:
        lines.append(f"    /* {w.name} ({w.widget_type}) */")
        if w.widget_type == WidgetType.BUTTON:
            lines.append(f'    GtkWidget *btn_{w.name} = gtk_button_new_with_label("{w.text}");')
            lines.append(f"    gtk_widget_set_size_request(btn_{w.name}, {w.width}, {w.height});")
            lines.append(f"    gtk_fixed_put(GTK_FIXED(fixed), btn_{w.name}, {w.x}, {w.y});")
            lines.append(f'    g_signal_connect(btn_{w.name}, "clicked", G_CALLBACK({w.event_handler}), NULL);')

        elif w.widget_type == WidgetType.LABEL:
            lines.append(f'    GtkWidget *lbl_{w.name} = gtk_label_new("{w.text}");')
            lines.append(f"    gtk_widget_set_size_request(lbl_{w.name}, {w.width}, {w.height});")
            lines.append(f"    gtk_fixed_put(GTK_FIXED(fixed), lbl_{w.name}, {w.x}, {w.y});")

        elif w.widget_type == WidgetType.ENTRY:
            lines.append(f"    GtkWidget *ent_{w.name} = gtk_entry_new();")
            lines.append(f'    gtk_entry_set_text(GTK_ENTRY(ent_{w.name}), "{w.text}");')
            lines.append(f"    gtk_widget_set_size_request(ent_{w.name}, {w.width}, {w.height});")
            lines.append(f"    gtk_fixed_put(GTK_FIXED(fixed), ent_{w.name}, {w.x}, {w.y});")

        elif w.widget_type == WidgetType.SLIDER:
            lines.append(f"    GtkWidget *scale_{w.name} = gtk_scale_new_with_range(GTK_ORIENTATION_HORIZONTAL, {w.min_val}, {w.max_val}, 1.0);")
            lines.append(f"    gtk_range_set_value(GTK_RANGE(scale_{w.name}), {w.value or 50.0});")
            lines.append(f"    gtk_widget_set_size_request(scale_{w.name}, {w.width}, {w.height});")
            lines.append(f"    gtk_fixed_put(GTK_FIXED(fixed), scale_{w.name}, {w.x}, {w.y});")

        elif w.widget_type == WidgetType.CHECKBOX:
            lines.append(f'    GtkWidget *chk_{w.name} = gtk_check_button_new_with_label("{w.text}");')
            if w.value:
                lines.append(f"    gtk_toggle_button_set_active(GTK_TOGGLE_BUTTON(chk_{w.name}), TRUE);")
            lines.append(f"    gtk_fixed_put(GTK_FIXED(fixed), chk_{w.name}, {w.x}, {w.y});")

        elif w.widget_type == WidgetType.PROGRESSBAR:
            lines.append(f"    GtkWidget *pb_{w.name} = gtk_progress_bar_new();")
            frac = float(w.value or 50.0) / 100.0
            lines.append(f"    gtk_progress_bar_set_fraction(GTK_PROGRESS_BAR(pb_{w.name}), {frac:.2f});")
            lines.append(f"    gtk_widget_set_size_request(pb_{w.name}, {w.width}, {w.height});")
            lines.append(f"    gtk_fixed_put(GTK_FIXED(fixed), pb_{w.name}, {w.x}, {w.y});")

        lines.append("")

    lines.append("    gtk_widget_show_all(window);")
    lines.append("}\n")
    lines.append("int main(int argc, char **argv) {")
    lines.append("    GtkApplication *app;")
    lines.append("    int status;\n")
    lines.append(f'    app = gtk_application_new("org.elfgui.{project.name.lower()}", G_APPLICATION_DEFAULT_FLAGS);')
    lines.append("    g_signal_connect(app, \"activate\", G_CALLBACK(activate), NULL);")
    lines.append("    status = g_application_run(G_APPLICATION(app), argc, argv);")
    lines.append("    g_object_unref(app);")
    lines.append("    return status;")
    lines.append("}")
    return "\n".join(lines)
