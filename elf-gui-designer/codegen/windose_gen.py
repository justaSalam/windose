"""
Native Windose OS ELF C Code Generator.
Generates C programs specifically designed for the Windose OS kernel v10 ELF loader
using the official kernel.h k_* GUI APIs.
"""

from core.models import Project, Widget, WidgetType


def _hex_to_argb(hex_str: str, default: str = "0xFF161E2E") -> str:
    clean = hex_str.lstrip("#")
    if len(clean) == 6:
        return f"0xFF{clean.upper()}"
    elif len(clean) == 8:
        return f"0x{clean.upper()}"
    return default


def generate_windose_c(project: Project) -> str:
    """Generates native Windose OS C program code utilizing kernel.h APIs."""
    lines = []
    lines.append("/**")
    lines.append(f" * Generated by ELF Studio - Native Windose OS ELF Program")
    lines.append(f" * Target: Windose Kernel API v10 (Cosmos NativeAOT)")
    lines.append(f" * Include: kernel.h (System/ELF/programs/include/kernel.h)")
    lines.append(f" * Screen: {project.name} ({project.canvas_width}x{project.canvas_height})")
    lines.append(" */\n")
    lines.append("#include <stdio.h>")
    lines.append("#include <stdlib.h>")
    lines.append("#include <string.h>")
    lines.append('#include "kernel.h"\n')

    # Widget handle declarations
    lines.append("/* Component Handles */")
    lines.append("static handle_t main_win = 0;")
    for w in project.widgets:
        if w.widget_type not in (WidgetType.PANEL, WidgetType.SEPARATOR):
            lines.append(f"static handle_t h_{w.name} = 0;")
    lines.append("")

    # Event handlers
    lines.append("/* Signal Callbacks */")
    seen_handlers = set()
    for w in project.widgets:
        if w.widget_type in (
            WidgetType.BUTTON, WidgetType.CHECKBOX, WidgetType.SWITCH,
            WidgetType.RADIO, WidgetType.DROPDOWN, WidgetType.LISTBOX,
            WidgetType.NUMERIC, WidgetType.TABS, WidgetType.COLORPICKER
        ):
            handler = w.event_handler or f"on_{w.name}_event"
            if handler not in seen_handlers:
                seen_handlers.add(handler)
                lines.append(f"static void {handler}(void) {{")
                lines.append(f'    k_write_file("/dev/log", "[EVENT] {handler} dispatched\\n", 0);')
                if w.widget_type in (WidgetType.CHECKBOX, WidgetType.SWITCH, WidgetType.RADIO):
                    lines.append(f"    int checked = k_get_checked(h_{w.name});")
                    lines.append(f"    (void)checked;")
                elif w.widget_type == WidgetType.NUMERIC:
                    lines.append(f"    int num_val = k_numeric_get(h_{w.name});")
                    lines.append(f"    (void)num_val;")
                elif w.widget_type == WidgetType.DROPDOWN:
                    lines.append(f"    int sel_idx = k_combo_get_selected(h_{w.name});")
                    lines.append(f"    (void)sel_idx;")
                elif w.widget_type == WidgetType.LISTBOX:
                    lines.append(f"    int sel_item = k_list_get_selected(h_{w.name});")
                    lines.append(f"    (void)sel_item;")
                elif w.widget_type == WidgetType.TABS:
                    lines.append(f"    int active_tab = k_tab_get_selected(h_{w.name});")
                    lines.append(f"    (void)active_tab;")
                elif w.widget_type == WidgetType.COLORPICKER:
                    lines.append(f"    int color_val = k_colorpicker_get(h_{w.name});")
                    lines.append(f"    (void)color_val;")
                elif w.widget_type == WidgetType.BUTTON:
                    lines.append(f"    // Action logic for button {w.name}")
                lines.append("}\n")

    # Main Entry Point
    lines.append("int main(int argc, char **argv) {")
    lines.append(f'    main_win = k_create_window({project.canvas_width}, {project.canvas_height}, "{project.name}");')
    lines.append("    if (!main_win) return 1;\n")

    for w in project.widgets:
        lines.append(f"    /* {w.name} ({w.widget_type}) */")

        if w.widget_type == WidgetType.PANEL:
            argb = _hex_to_argb(w.bg_color, "0xFF161E2E")
            lines.append(f"    k_fill_rect(main_win, {w.x}, {w.y}, {w.width}, {w.height}, {argb});")

        elif w.widget_type == WidgetType.BUTTON:
            lines.append(f'    h_{w.name} = k_create_button(main_win, {w.x}, {w.y}, {w.width}, {w.height}, "{w.text}");')

        elif w.widget_type == WidgetType.LABEL:
            lines.append(f'    h_{w.name} = k_create_label(main_win, {w.x}, {w.y}, "{w.text}");')

        elif w.widget_type == WidgetType.ENTRY:
            lines.append(f"    h_{w.name} = k_create_textfield(main_win, {w.x}, {w.y}, {w.width});")
            lines.append(f"    k_textfield_setup(h_{w.name}, 256, 0, 0);")
            if w.text or w.placeholder:
                init_txt = w.text or w.placeholder
                lines.append(f'    k_set_text(h_{w.name}, "{init_txt}");')

        elif w.widget_type == WidgetType.TEXTAREA:
            lines.append(f"    h_{w.name} = k_create_textfield(main_win, {w.x}, {w.y}, {w.width});")
            lines.append(f"    k_textfield_setup(h_{w.name}, 4096, 0, 0);")
            lines.append(f"    k_textfield_set_multiline(h_{w.name}, 1);")
            clean_txt = (w.text or "").replace('"', '\\"').replace("\n", "\\n")
            lines.append(f'    k_set_text(h_{w.name}, "{clean_txt}");')

        elif w.widget_type in (WidgetType.CHECKBOX, WidgetType.SWITCH):
            lines.append(f'    h_{w.name} = k_create_checkbox(main_win, {w.x}, {w.y}, "{w.text}");')
            if w.value:
                lines.append(f"    k_set_checked(h_{w.name}, 1);")

        elif w.widget_type == WidgetType.RADIO:
            grp = w.group or "group1"
            lines.append(f'    h_{w.name} = k_create_radio(main_win, {w.x}, {w.y}, "{w.text}", "{grp}");')
            if w.value:
                lines.append(f"    k_set_checked(h_{w.name}, 1);")

        elif w.widget_type == WidgetType.SLIDER:
            val = int(w.value if w.value is not None else 50)
            lines.append(f"    h_{w.name} = k_create_slider(main_win, {w.x}, {w.y}, {w.width}, 1, {int(w.min_val)}, {int(w.max_val)}, {val});")

        elif w.widget_type == WidgetType.PROGRESSBAR:
            lines.append(f"    h_{w.name} = k_create_progress(main_win, {w.x}, {w.y}, {w.width}, {w.height});")
            lines.append(f"    k_progress_setup(h_{w.name}, {int(w.min_val)}, {int(w.max_val)});")
            lines.append(f"    k_progress_set(h_{w.name}, {int(w.value if w.value is not None else 50)});")

        elif w.widget_type == WidgetType.DROPDOWN:
            lines.append(f"    h_{w.name} = k_create_combo(main_win, {w.x}, {w.y}, {w.width});")
            opts = w.options or ["Option 1", "Option 2"]
            for opt in opts:
                lines.append(f'    k_combo_add_item(h_{w.name}, "{opt}");')

        elif w.widget_type == WidgetType.LISTBOX:
            lines.append(f"    h_{w.name} = k_create_listbox(main_win, {w.x}, {w.y}, {w.width}, {w.height});")
            col_name = w.text or "Items"
            lines.append(f'    k_list_add_column(h_{w.name}, "{col_name}", {w.width - 20});')
            items = w.items or ["Item 1", "Item 2", "Item 3"]
            for itm in items:
                lines.append(f'    k_list_add_item(h_{w.name}, "{itm}");')

        elif w.widget_type == WidgetType.DATAGRID:
            lines.append(f"    h_{w.name} = k_grid_create(main_win, {w.x}, {w.y}, {w.width}, {w.height});")
            cols = w.columns or ["ID", "Name", "Status"]
            cw = max(40, (w.width - 24) // max(1, len(cols)))
            for col in cols:
                lines.append(f'    k_grid_add_column(h_{w.name}, "{col}", {cw});')
            # Add sample rows
            lines.append(f'    k_grid_add_row(h_{w.name}, "1\tAlpha\tActive", 14);')
            lines.append(f'    k_grid_add_row(h_{w.name}, "2\tBeta\tStandby", 14);')

        elif w.widget_type == WidgetType.NUMERIC:
            val = int(w.value if w.value is not None else 0)
            step = int(w.step if w.step else 1)
            lines.append(f"    h_{w.name} = k_numeric_create(main_win, {w.x}, {w.y}, {w.width}, {int(w.min_val)}, {int(w.max_val)}, {step}, {val});")

        elif w.widget_type == WidgetType.SEPARATOR:
            argb = _hex_to_argb(w.bg_color, "0xFF334155")
            if w.orientation == "vertical":
                lines.append(f"    k_fill_rect(main_win, {w.x + w.width//2}, {w.y}, 2, {w.height}, {argb});")
            else:
                lines.append(f"    k_fill_rect(main_win, {w.x}, {w.y + w.height//2}, {w.width}, 2, {argb});")

        elif w.widget_type == WidgetType.TABS:
            lines.append(f"    h_{w.name} = k_create_tabs(main_win, {w.x}, {w.y}, {w.width}, {w.height});")
            pages = w.items or ["Page 1", "Page 2"]
            for pg in pages:
                lines.append(f'    k_tab_add_page(h_{w.name}, "{pg}");')

        elif w.widget_type == WidgetType.IMAGE:
            argb = _hex_to_argb(w.bg_color, "0xFF0F172A")
            lines.append(f"    k_fill_rect(main_win, {w.x}, {w.y}, {w.width}, {w.height}, {argb});")
            lines.append(f'    h_{w.name} = k_create_label(main_win, {w.x + 8}, {w.y + w.height - 20}, "{w.text}");')

        elif w.widget_type == WidgetType.CANVAS:
            lines.append(f"    h_{w.name} = k_create_canvas(main_win, {w.x}, {w.y}, {w.width}, {w.height});")

        elif w.widget_type == WidgetType.COLORPICKER:
            lines.append(f"    h_{w.name} = k_colorpicker_create(main_win, {w.x}, {w.y});")
            argb = _hex_to_argb(w.bg_color or str(w.value or ""), "0xFF2563EB")
            lines.append(f"    k_colorpicker_set(h_{w.name}, {argb});")

        elif w.widget_type == WidgetType.STATUSBAR:
            lines.append(f"    h_{w.name} = k_statusbar_create(main_win, {w.x}, {w.y}, {w.width});")
            lines.append(f'    k_status_add_panel(h_{w.name}, "{w.text}", {w.width});')

        lines.append("")

    # Event Dispatch Loop
    lines.append("    /* Main Windose Event Loop */")
    lines.append("    for (;;) {")
    lines.append("        Event e;")
    lines.append("        while (k_poll_event(&e)) {")
    lines.append("            if (e.type == EV_CLOSE && e.handle == main_win) {")
    lines.append("                k_close(main_win);")
    lines.append("                return 0;")
    lines.append("            }")
    lines.append("            if (e.type == EV_CLICK) {")

    for w in project.widgets:
        if w.widget_type in (
            WidgetType.BUTTON, WidgetType.CHECKBOX, WidgetType.SWITCH,
            WidgetType.RADIO, WidgetType.DROPDOWN, WidgetType.LISTBOX,
            WidgetType.NUMERIC, WidgetType.TABS, WidgetType.COLORPICKER
        ):
            handler = w.event_handler or f"on_{w.name}_event"
            lines.append(f"                if (e.handle == h_{w.name}) {{")
            lines.append(f"                    {handler}();")
            lines.append("                }")

    lines.append("            }")
    lines.append("        }")
    lines.append("        k_sleep(10); // Prevent 100% CPU starvation")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines)
