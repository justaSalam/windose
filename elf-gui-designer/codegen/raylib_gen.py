"""
Raylib + Raygui C code generator.
Generates an immediate-mode C GUI program ready to compile into a native Linux ELF binary.
"""

from core.models import Project, Widget, WidgetType


def hex_to_raycolor(hex_str: str) -> str:
    """Converts #RRGGBB to (Color){ r, g, b, 255 }."""
    clean = hex_str.lstrip("#")
    if len(clean) == 6:
        r = int(clean[0:2], 16)
        g = int(clean[2:4], 16)
        b = int(clean[4:6], 16)
        return f"(Color){{ {r}, {g}, {b}, 255 }}"
    return "(Color){ 30, 41, 59, 255 }"


def generate_raylib_c(project: Project) -> str:
    """Generates Raylib C source code for the project."""
    lines = []
    lines.append("/**")
    lines.append(f" * Generated by ELF Studio - GUI Designer for ELF Programs")
    lines.append(f" * Target: Raylib / Raygui (Linux ELF / Cross-Platform)")
    lines.append(f" * Compile on Linux: gcc main.c -lraylib -lGL -lm -lpthread -ldl -lrt -lX11 -o {project.name.lower()}.elf")
    lines.append(" */\n")
    lines.append('#include "raylib.h"')
    lines.append("#define RAYGUI_IMPLEMENTATION")
    lines.append('#include "raygui.h"')
    lines.append("#include <stdio.h>\n")

    # State variables for controls
    lines.append("/* Interactive UI State */")
    for w in project.widgets:
        if w.widget_type == WidgetType.SLIDER:
            lines.append(f"static float val_{w.name} = {float(w.value or 50.0):.1f}f;")
        elif w.widget_type in (WidgetType.CHECKBOX, WidgetType.SWITCH):
            lines.append(f"static bool state_{w.name} = {'true' if w.value else 'false'};")
        elif w.widget_type == WidgetType.ENTRY:
            lines.append(f'static char text_{w.name}[128] = "{w.text}";')
            lines.append(f"static bool edit_{w.name} = false;")
        elif w.widget_type == WidgetType.DROPDOWN:
            lines.append(f"static int active_{w.name} = 0;")
            lines.append(f"static bool drop_edit_{w.name} = false;")
    lines.append("")

    # Main function
    lines.append("int main(void) {")
    lines.append(f'    InitWindow({project.canvas_width}, {project.canvas_height}, "{project.name} - Linux ELF GUI");')
    lines.append("    SetTargetFPS(60);\n")
    lines.append("    /* Apply dark palette */")
    lines.append("    GuiSetStyle(DEFAULT, BACKGROUND_COLOR, 0x0f172aff);")
    lines.append("    GuiSetStyle(DEFAULT, TEXT_COLOR_NORMAL, 0xf8fafcff);\n")
    lines.append("    while (!WindowShouldClose()) {")
    lines.append("        /* Update & Draw Frame */")
    lines.append("        BeginDrawing();")
    lines.append(f"        ClearBackground({hex_to_raycolor(project.bg_color)});\n")

    for w in project.widgets:
        rect = f"(Rectangle){{ {w.x}, {w.y}, {w.width}, {w.height} }}"
        if w.widget_type == WidgetType.PANEL:
            lines.append(f"        DrawRectangleRounded({rect}, 0.05f, 4, {hex_to_raycolor(w.bg_color)});")
            lines.append(f"        DrawRectangleRoundedLines({rect}, 0.05f, 4, 1.0f, {hex_to_raycolor(w.border_color)});")

        elif w.widget_type == WidgetType.LABEL:
            lines.append(f'        DrawText("{w.text}", {w.x}, {w.y}, {w.font_size}, {hex_to_raycolor(w.text_color)});')

        elif w.widget_type == WidgetType.BUTTON:
            lines.append(f'        if (GuiButton({rect}, "{w.text}")) {{')
            lines.append(f'            printf("[EVENT] {w.event_handler} clicked!\\n");')
            lines.append("        }")

        elif w.widget_type == WidgetType.SLIDER:
            lines.append(f'        GuiSlider({rect}, "{w.text}", TextFormat("%.0f", val_{w.name}), &val_{w.name}, {w.min_val}f, {w.max_val}f);')

        elif w.widget_type == WidgetType.PROGRESSBAR:
            lines.append(f'        GuiProgressBar({rect}, NULL, NULL, (float*)(&(float){{ {float(w.value or 50.0)/100.0:.2f}f }}), 0.0f, 1.0f);')

        elif w.widget_type == WidgetType.CHECKBOX:
            lines.append(f'        GuiCheckBox({rect}, "{w.text}", &state_{w.name});')

        elif w.widget_type == WidgetType.SWITCH:
            lines.append(f'        GuiToggle({rect}, state_{w.name} ? "ON" : "OFF", &state_{w.name});')

        elif w.widget_type == WidgetType.ENTRY:
            lines.append(f'        if (GuiTextBox({rect}, text_{w.name}, 128, edit_{w.name})) {{')
            lines.append(f'            edit_{w.name} = !edit_{w.name};')
            lines.append("        }")

        elif w.widget_type == WidgetType.STATUSBAR:
            lines.append(f"        DrawRectangle({w.x}, {w.y}, {w.width}, {w.height}, {hex_to_raycolor(w.bg_color)});")
            lines.append(f'        DrawText("{w.text}", {w.x + 10}, {w.y + 6}, {w.font_size}, {hex_to_raycolor(w.text_color)});')

    lines.append("\n        EndDrawing();")
    lines.append("    }\n")
    lines.append("    CloseWindow();")
    lines.append("    return 0;")
    lines.append("}")
    return "\n".join(lines)
